// Deterministic content variation utilities for region pages.
// Uses a slug-derived hash to pick different items / phrasing per page,
// so 1700+ region pages don't share identical body copy.

function hash(str: string): number {
  let h = 5381;
  for (let i = 0; i < str.length; i++) {
    h = ((h << 5) + h) ^ str.charCodeAt(i);
  }
  return h >>> 0;
}

function shuffled<T>(arr: T[], seed: number): T[] {
  const a = [...arr];
  let s = seed || 1;
  for (let i = a.length - 1; i > 0; i--) {
    s = (s * 1664525 + 1013904223) >>> 0;
    const j = s % (i + 1);
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

export function pickN<T>(slug: string, pool: T[], n: number, salt = ""): T[] {
  return shuffled(pool, hash(slug + "::" + salt)).slice(0, n);
}

export function pickOne<T>(slug: string, pool: T[], salt = ""): T {
  return pickN(slug, pool, 1, salt)[0];
}

