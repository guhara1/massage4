export function makeTitle(slug: string, geo: string): string {
  const fn = pickOne(slug, TITLE_VARIANTS, "title");
  return fn(geo);
}

export function makeDescription(args: {
  slug: string;
  full: string;
  short: string;
  count?: number;
  countLabel?: string;
  hours: string;
}): string {
  const fn = pickOne(args.slug, DESCRIPTION_VARIANTS, "desc");
  return fn(args);
}
